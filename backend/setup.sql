-- 9.1 Tabla de sedes: los puntos donde se atiende a los estudiantes.
-- El admin puede agregar, renombrar y quitar sedes desde el panel, y
-- la reserva y el registro de beneficiarios las usan dinamicamente.
create table if not exists sedes (
  id bigint generated by default as identity primary key,
  nombre text not null unique,
  created_at timestamptz default now()
);

-- 9.2 Tabla de sobrantes: lo que el personal de cocina reporta que
-- quedo sin servir cada dia, por sede y jornada. Se registran porciones
-- y peso en kilogramos. Hay una sola fila por fecha + sede + jornada:
-- si se vuelve a guardar, se sobrescribe.
create table if not exists sobrantes (
  id bigint generated by default as identity primary key,
  fecha date not null,
  sede text not null,
  turno text not null,
  porciones integer,
  peso_kg numeric,
  creado_por text,
  created_at timestamptz default now(),
  updated_at timestamptz default now(),
  unique (fecha, sede, turno)
);

-- 10. Tabla de usuarios: cuentas con login para el panel.
-- Cada rol ve solo las secciones que le corresponden:
--   admin        -> todo el panel
--   cocina       -> panel de cocina y menu
--   profesor     -> beneficiarios, asistencia y avisos
--   coordinador  -> avisos, galeria, instituciones, mensajes
--   estudiante   -> reserva propia, mis reservas y valorar platos
-- La clave se guarda SIEMPRE hasheada (sal:hash). El usuario es unico
-- (para estudiantes coincide con su numero de documento).
create table if not exists usuarios (
  id bigint generated by default as identity primary key,
  nombre text not null,
  usuario text not null unique,
  clave_hash text not null,
  rol text not null default 'estudiante',
  activo boolean default true,
  created_at timestamptz default now()
);

-- Las claves/PINs viven SOLO en clave_hash (el login verifica contra
-- el hash). La antigua columna "clave" en texto plano se elimino:
-- guardarla anulaba el hasheo y exponia todas las claves en un volcado
-- de la base. Para cambiar una clave se usa la edicion del panel.
alter table usuarios drop column if exists clave;

-- 10.2 Grupo asignado a cada profesor: sede + turno + grado. Con estos
-- datos la pestana Asistencia le muestra SOLO los reservados de su grupo
-- (los estudiantes de esa sede, turno y grado) para marcar quien asistio.
alter table usuarios add column if not exists sede text;
alter table usuarios add column if not exists turno text;
alter table usuarios add column if not exists grado text;

-- 10.3 Tabla de incidentes: reportes que hace el profesor sobre un
-- estudiante de su grupo (un incidente o una alergia). Cada reporte
-- llega al coordinador (y al admin), que puede marcarlo como resuelto.
-- "documento" identifica al estudiante y "reportado_por" guarda el
-- usuario del profesor que lo reporto, para que cada profesor vea
-- solo los que el mismo registro.
create table if not exists incidentes (
  id bigint generated by default as identity primary key,
  tipo text not null,
  estudiante text not null,
  documento text,
  sede text not null,
  grado text,
  descripcion text not null,
  fecha date not null,
  reportado_por text not null,
  resuelto boolean default false,
  resuelto_por text,
  resuelto_at timestamptz,
  created_at timestamptz default now()
);

-- Los reportes pueden llevar una foto adjunta (la URL la guarda el
-- backend en Supabase Storage al subirla desde el panel).
alter table incidentes add column if not exists imagen text;

-- 10.4 Avisos y menú: flujo borrador -> publicado. El coordinador (o el
-- admin) aprueba lo que redactó otro rol; la web solo muestra publicado.
alter table avisos add column if not exists estado text default 'publicado';
alter table menus add column if not exists estado text default 'publicado';

-- 10.41 La variante agrupa el platillo por tipo de dieta: Estandar,
-- Celiaco (sin gluten), Vegetariano y Vegano. La usa la pestana Menu
-- para filtrar el catalogo y los beneficiarios con preferencia la ven
-- primero en su reserva.
alter table menus add column if not exists variante text default 'Estandar';

-- 10.5 Tabla de settings: configuracion del sistema que se cambia desde
-- el panel sin tocar el codigo. Guarda pares clave-valor:
--   hora_limite_reserva: "08:00" (a esa hora se cierran las reservas y
--     cancelaciones para el MISMO dia).
--   cupos_sede: JSON con el cupo maximo de reservas por sede y fecha,
--     ej: {"Sede A": 50, "Sede B": 40}.
create table if not exists settings (
  clave text primary key,
  valor text,
  updated_at timestamptz default now()
);

-- Valores por defecto: limite de reserva a las 8am y sin cupos. El
-- admin los cambia desde el panel (pestana Configuracion).
insert into settings (clave, valor) values
  ('hora_limite_reserva', '08:00'),
  ('cupos_sede', '{}')
on conflict (clave) do nothing;

-- 10.6 Tabla de turnos de cocina: que persona del personal de cocina
